const months = [
  "january", "february", "march", "april", "may", "june",
  "july", "august", "september", "october", "november", "december",
];
const days = ["sunday", "monday", "tuesday", "wednesday", "thursday", "friday", "saturday"];

export function fileManagerLocale(t) {
  const translate = (key) => t(key) || t(key, { lng: "en" });
  const groups = Object.fromEntries(Object.entries(svarKeys).map(([group, keys]) => [
    group,
    Object.fromEntries(Object.entries(keys).map(([label, key]) => [label, translate(`${group}.${key}`)])),
  ]));
  const calendar = {
    monthFull: months.map((month) => translate(`calendar.monthFull.${month}`)),
    monthShort: months.map((month) => translate(`calendar.monthShort.${month}`)),
    dayFull: days.map((day) => translate(`calendar.dayFull.${day}`)),
    dayShort: days.map((day) => translate(`calendar.dayShort.${day}`)),
    hours: translate("calendar.hours"),
    minutes: translate("calendar.minutes"),
    done: translate("calendar.done"),
    clear: translate("calendar.clear"),
    today: translate("calendar.today"),
    am: [translate("calendar.am"), translate("calendar.amUpper")],
    pm: [translate("calendar.pm"), translate("calendar.pmUpper")],
    weekStart: 1,
    clockFormat: 24,
  };
  return {
    ...groups,
    calendar,
    formats: { dateFormat: "%d/%m/%Y", timeFormat: "%H:%i", monthYearFormat: "%F %Y", yearFormat: "%Y" },
    lang: "fr-FR",
  };
}
